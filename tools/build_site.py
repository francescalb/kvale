"""Assemble the static web app in ``_site/`` and optionally serve it.

    python tools/build_site.py             # build _site/
    python tools/build_site.py --serve     # build, then serve on http://localhost:8000/
    python tools/build_site.py --serve 8765

The site is ``web/`` plus the browser-safe part of ``src/kvale`` (the package
``__init__`` and ``kvale.core``; not the Tkinter GUI). The ``[files]`` table of
``pyscript.toml`` is generated from the Python files found, so it never needs
editing by hand. Only the standard library is used.
"""

from __future__ import annotations

import argparse
import functools
import http.server
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
SRC = ROOT / "src"
DEFAULT_OUT = ROOT / "_site"
# Parts of src/ that run in the browser.
CORE_SOURCES = ("kvale/__init__.py", "kvale/core")
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".mypy_cache", ".ruff_cache")


def _python_files(out: Path) -> list[str]:
    """Paths (relative to ``out``, with /) of the modules PyScript must fetch."""
    files = sorted(path.relative_to(out).as_posix() for path in out.rglob("*.py"))
    return [path for path in files if path != "main.py"]  # main.py is the <script src>


def files_table(paths: list[str]) -> str:
    lines = [
        "",
        "# Generated by tools/build_site.py: fetched URL = path in Pyodide's filesystem.",
        "[files]",
    ]
    lines += [f'"{path}" = "./{path}"' for path in paths]
    return "\n".join(lines) + "\n"


def build(out: Path = DEFAULT_OUT) -> Path:
    """Build the site into ``out`` (replacing it) and return ``out``."""
    if out.exists():
        # Only replace an earlier build (marked by .nojekyll) or an empty folder.
        if any(out.iterdir()) and not (out / ".nojekyll").exists():
            raise SystemExit(f"Refusing to replace {out}: it is not an earlier site build")
        shutil.rmtree(out)
    shutil.copytree(WEB, out, ignore=IGNORE)
    for source in CORE_SOURCES:
        src_path = SRC / source
        if src_path.is_dir():
            shutil.copytree(src_path, out / source, ignore=IGNORE)
        else:
            (out / source).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src_path, out / source)

    config = out / "pyscript.toml"
    config.write_text(
        config.read_text(encoding="utf-8") + files_table(_python_files(out)), encoding="utf-8"
    )
    # GitHub Pages: serve files as they are (no Jekyll processing).
    (out / ".nojekyll").touch()
    return out


class _QuietHandler(http.server.SimpleHTTPRequestHandler):
    def end_headers(self) -> None:
        # Always fetch the latest build while developing.
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def log_message(self, format: str, *args: object) -> None:
        # Only report failed requests (args are request line, status, size).
        if len(args) == 3 and str(args[1]).startswith(("4", "5")):
            super().log_message(format, *args)


def serve(directory: Path, port: int) -> None:
    handler = functools.partial(_QuietHandler, directory=str(directory))
    with http.server.ThreadingHTTPServer(("127.0.0.1", port), handler) as server:
        print(f"Serving {directory} at http://localhost:{port}/  (Ctrl+C to stop)", flush=True)
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            print()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--serve",
        nargs="?",
        type=int,
        const=8000,
        metavar="PORT",
        help="serve the site after building (default port 8000)",
    )
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output folder")
    args = parser.parse_args(argv)
    out = build(args.out.resolve())
    print(f"Built {out}")
    if args.serve is not None:
        serve(out, args.serve)
    return 0


if __name__ == "__main__":
    sys.exit(main())
